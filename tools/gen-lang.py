#!/usr/bin/env python3
"""Builds the English string table from upstream 7-Zip .rc/.h resources.

Upstream code calls LangString(IDS_...) -> NWindows::MyLoadString(id) when
built without Z7_LANG. src/core/Lang.cpp answers those lookups from the table
this script writes, so ported code keeps upstream's resource IDs and texts.

usage: gen-lang.py <7zip-src-root> <output.inc>
"""
import os
import re
import sys

root, out = sys.argv[1], sys.argv[2]
dirs = [os.path.join(root, 'CPP/7zip/UI', d) for d in ('FileManager', 'GUI', 'Common', 'Explorer')]

defines = {}
for d in dirs:
    for fn in sorted(os.listdir(d)):
        if fn.endswith('.h'):
            text = open(os.path.join(d, fn), encoding='latin-1').read()
            for name, val in re.findall(r'#define\s+(ID\w+)\s+(\d+)\b', text):
                defines.setdefault(name, int(val))

STR = r'"((?:[^"]|"")*)"'
patterns = [
    # STRINGTABLE:  IDS_X  "text"
    re.compile(r'^\s*(ID\w+)\s*,?\s*' + STR + r'\s*$', re.M),
    # MENUITEM "text", IDM_X
    re.compile(r'MENUITEM\s+' + STR + r'\s*,\s*(ID\w+)'),
    # POPUP "text" MY_MENUITEM_ID(IDM_X)
    re.compile(r'POPUP\s+' + STR + r'\s+MY_MENUITEM_ID\((ID\w+)\)'),
    # dialog controls: LTEXT "text", IDT_X, ...
    re.compile(r'\b(?:LTEXT|RTEXT|CTEXT|PUSHBUTTON|DEFPUSHBUTTON|GROUPBOX|CONTROL|'
               r'AUTOCHECKBOX|AUTORADIOBUTTON|CHECKBOX|RADIOBUTTON)\s+' + STR + r'\s*,\s*(ID\w+)'),
]

rc_texts = []
for d in dirs:
    for fn in sorted(os.listdir(d)):
        if fn.endswith('.rc'):
            text = open(os.path.join(d, fn), encoding='latin-1').read()
            rc_texts.append(re.sub(r'^\s*//.*$', '', text, flags=re.M))

# Priority like upstream's lookups: STRINGTABLE entries first, then menu
# items, then dialog captions and control texts (IDs can repeat across
# these kinds; e.g. 1000 + kpid property names vs. dialog control IDs).
strings = {}
for i, pat in enumerate(patterns):
    for text in rc_texts:
        for m in pat.finditer(text):
            name, s = (m.group(1), m.group(2)) if i == 0 else (m.group(2), m.group(1))
            if name in defines and s:
                strings.setdefault(defines[name], s)
for text in rc_texts:
    # IDD_X DIALOG ... CAPTION "text"
    for name, s in re.findall(r'^(IDD_\w+)\s+DIALOG\b.*?\n(?:.*\n){0,3}?\s*CAPTION\s+' + STR, text, re.M):
        if name in defines and s:
            strings.setdefault(defines[name], s)

def c_escape(s):
    s = s.replace('""', '"')
    res = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == '\\' and i + 1 < len(s):
            res.append(s[i:i + 2]); i += 2; continue
        if c == '"':
            res.append('\\"')
        elif ord(c) > 126:
            res.append('\\x%04x' % ord(c))
        else:
            res.append(c)
        i += 1
    return ''.join(res)

os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w') as f:
    f.write('// Generated by tools/gen-lang.py -- do not edit.\n')
    for k in sorted(strings):
        f.write('{ %d, L"%s" },\n' % (k, c_escape(strings[k])))
print('gen-lang: %d strings' % len(strings))
