#!/bin/sh
# Regenerates cmake/7zcore-sources.cmake from the upstream Linux 7zz build
# (Bundles/Alone2), minus the console UI. The Agent layer is not listed: it
# is ported in src/agent/ because upstream never builds it on POSIX.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
UP="$ROOT/external/7zip"
OUT="$ROOT/cmake/7zcore-sources.cmake"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# Dry run with O= pointed outside the submodule so it stays clean.
(cd "$UP/CPP/7zip/Bundles/Alone2" && make -s -n -f ../../cmpl_gcc.mak O="$TMP/o") \
  | grep -oE '(\.\./)+[^ ]+\.(c|cpp)' \
  | sed 's#^\(\.\./\)*##' \
  | sort -u > "$TMP/list"

# Map "../../X" (relative to CPP/7zip/Bundles/Alone2) to repo-relative paths.
: > "$TMP/srcs"
while read -r f; do
  for base in CPP/7zip CPP .; do
    if [ -f "$UP/$base/$f" ]; then echo "$base/$f" | sed 's#^\./##' >> "$TMP/srcs"; break; fi
  done
done < "$TMP/list"

grep -v '/UI/Console/' "$TMP/srcs" > "$TMP/core"
# Extra upstream files the Agent needs that 7zz does not link.
for f in CPP/Windows/DLL.cpp CPP/Windows/FileSystem.cpp CPP/7zip/UI/Common/WorkDir.cpp CPP/7zip/UI/Common/ArchiveName.cpp; do
  (cd "$UP" && ls $f) >> "$TMP/core"
done
sort -u -o "$TMP/core" "$TMP/core"

# unRAR support is a hard requirement.
for need in Archive/Rar/RarHandler.cpp Archive/Rar/Rar5Handler.cpp \
    Compress/Rar1Decoder.cpp Compress/Rar2Decoder.cpp Compress/Rar3Decoder.cpp \
    Compress/Rar3Vm.cpp Compress/Rar5Decoder.cpp Compress/RarCodecsRegister.cpp \
    Crypto/Rar20Crypto.cpp Crypto/RarAes.cpp Crypto/Rar5Aes.cpp; do
  grep -q "/$need\$" "$TMP/core" || { echo "missing RAR source: $need" >&2; exit 1; }
done

{
  echo "# Generated by tools/gen-core-sources.sh -- do not edit."
  echo "set(SEVENZIP_CORE_SOURCES"
  sed 's#^#  ${SEVENZIP_DIR}/#' "$TMP/core"
  echo ")"
} > "$OUT"
echo "wrote $(grep -c SEVENZIP_DIR "$OUT") sources to $OUT"
